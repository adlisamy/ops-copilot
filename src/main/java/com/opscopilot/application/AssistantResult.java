package com.opscopilot.application;

import java.util.List;

/**
 * Structured output from the AI assistant — a typed representation of the LLM's response.
 *
 * <p>This record is used with Spring AI's {@code .entity()} method for type-safe deserialization.
 * When you call {@code chatClient.prompt()...entity(AssistantResult.class)}, Spring AI does two things:</p>
 *
 * <ol>
 *   <li><b>Instructs the LLM</b> — Spring AI automatically adds a system instruction telling the
 *       LLM to output JSON matching the structure of this class (with fields: reply, suggestions, tone).</li>
 *   <li><b>Deserializes the response</b> — Once the LLM returns JSON, Spring AI parses it into
 *       this Java object using Jackson (the JSON library behind Spring Boot).</li>
 * </ol>
 *
 * <h3>Why use a Java record?</h3>
 * <p>Records (introduced in Java 14) are perfect for data carriers like this. They are immutable,
 * concise, and automatically provide {@code getter}, {@code equals()}, {@code hashCode()},
 * and {@code toString()} methods. For Spring AI structured output, the record's constructor
 * parameters define the JSON schema that the LLM must follow.</p>
 *
 * <h3>How the LLM "knows" the structure:</h3>
 * <p>Spring AI inspects the class definition at runtime and generates a JSON schema. This schema
 * is included in the system prompt sent to the LLM. The model then formats its response as JSON
 * matching that schema. If {@code validateSchema()} is called (as in {@link ChatAssistant}),
 * Spring AI verifies that the returned JSON actually matches the expected structure.</p>
 *
 * <h3>Example LLM output:</h3>
 * <pre>
 * {
 *   "reply": "To check disk usage, run 'df -h' on Linux.",
 *   "suggestions": ["How do I clean up disk space?", "What is 'df -h' showing?"],
 *   "tone": "informative"
 * }
 * </pre>
 *
 * @param reply       the main text response from the AI assistant
 * @param suggestions a list of follow-up questions or related actions the user might explore
 * @param tone        the emotional tone of the response (e.g., "informative", "cautious", "helpful")
 *                   — useful for UI decisions like showing warning icons or color-coding
 *
 * @see ChatAssistant#ask(String)
 * @see ChatAssistant#askWithMemory(String, String)
 */
public record AssistantResult(
        /**
         * The main text response from the AI assistant.
         *
         * <p>This is the primary answer to the user's question. The system prompt instructs
         * the LLM to be concise, technical, and actionable.</p>
         */
        String reply,

        /**
         * Follow-up suggestions generated by the AI to guide the conversation.
         *
         * <p>The system prompt asks the LLM to provide 2-3 follow-up suggestions.
         * These can be displayed as clickable buttons or chips in a chat UI,
         * encouraging the user to continue the conversation.</p>
         *
         * <p>This list may be {@code null} if the LLM fails to include suggestions
         * in its response, so callers should handle the null case.</p>
         */
        List<String> suggestions,

        /**
         * The emotional or stylistic tone of the response.
         *
         * <p>Common values include "informative", "cautious", "helpful", "urgent", etc.
         * This metadata can be used by the UI to adjust presentation — for example,
         * showing a warning icon when the tone is "cautious" or "urgent".</p>
         */
        String tone
) {
}
